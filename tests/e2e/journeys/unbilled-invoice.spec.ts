/* global document */
import { expect, test } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import { createClientWithContact, json, loginAdminThroughUi } from './support';

test('approved work becomes one confirmed draft, survives receipt recovery and releases only after void undo', async ({ page }) => {
  await loginAdminThroughUi(page);
  const api = page.request;
  const { client, suffix } = await createClientWithContact(api, 'Unbilled work QA');
  const project = await json(await api.post('/api/projects', { data: { clientId: client.id, name: `Billing project ${suffix}`, portfolio: 'FREELANCE' } }), 201);
  const description = `Approved design ${suffix}`;
  const time = await json(await api.post('/api/time-entries', { data: { projectId: project.id, duration: 60, billable: true, description, date: new Date().toISOString() } }), 201);
  await json(await api.patch(`/api/timesheets/${time.id}/approve`));
  const expenseDescription = `Materials ${suffix}`;
  await json(await api.post('/api/expenses', { data: { clientId: client.id, description: expenseDescription, currency: 'CAD', amount: 10, billable: true, category: 'SOFTWARE', date: new Date().toISOString().slice(0, 10) } }));
  await page.goto('/invoices');
  await page.getByText('More actions', { exact: true }).click();
  await page.getByRole('button', { name: 'Bill approved work' }).click();
  await page.getByLabel('Find client').fill(client.name);
  await expect(page.getByRole('combobox', { name: 'Client', exact: true }).locator('option', { hasText: client.name })).toHaveCount(1);
  await page.getByRole('combobox', { name: 'Client', exact: true }).selectOption(client.id);
  await page.getByLabel('Invoice title').fill(`Reviewed draft ${suffix}`);
  await page.getByRole('button', { name: 'Load unbilled work', exact: true }).click();
  await page.getByRole('checkbox', { name: description, exact: true }).check();
  await page.getByLabel(`Hourly rate for ${description} (CAD)`).fill('50');
  await page.getByRole('checkbox', { name: expenseDescription, exact: true }).check();
  await page.getByRole('button', { name: 'Preview draft invoice', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Confirm draft creation' })).toBeVisible();
  await expect(page.getByText('Total: $60.00 CAD', { exact: false })).toBeVisible();
  for (const width of [1280, 390, 320]) {
    await page.setViewportSize({ width, height: 844 });
    expect((await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa']).analyze()).violations).toEqual([]);
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(width + 1);
  }
  const actionId = new URL(page.url()).searchParams.get('action');
  expect(actionId).toBeTruthy();
  await page.getByRole('button', { name: 'Confirm draft creation' }).focus();
  await page.keyboard.press('Enter');
  await expect(page.getByRole('link', { name: 'Open invoice' })).toBeVisible();
  const invoicePath = await page.getByRole('link', { name: 'Open invoice' }).getAttribute('href');
  const invoiceId = invoicePath!.split('/').at(-1);
  const invoice = await json(await api.get(`/api/invoices/${invoiceId}`));
  expect(invoice.status).toBe('DRAFT'); expect(invoice.total).toBe(60);
  expect(invoice.billingSources.lineItems.map((line: any) => line.source.id)).toContain(time.id);
  await page.reload();
  await page.getByRole('button', { name: 'Retrieve receipt' }).click();
  await expect(page.getByRole('link', { name: 'Open invoice' })).toHaveAttribute('href', invoicePath!);
  const replay = await json(await api.post('/api/invoices/unbilled/tools/confirm_action', { data: { actionId } }));
  expect(replay.data.idempotent).toBe(true); expect(replay.data.action.result.id).toBe(invoiceId);
  await page.goto(`/invoices/${invoiceId}`);
  await page.getByText('Original billed work', { exact: true }).click();
  await expect(page.getByText(`TIME: ${time.id}`, { exact: false })).toBeVisible();
  await json(await api.delete(`/api/invoices/${invoiceId}`));
  const tooSoon = await api.post('/api/invoices/unbilled/tools/preview_unbilled_release', { data: { invoiceId } });
  expect(tooSoon.status()).toBe(409);
  await expect.poll(async () => (await api.post('/api/invoices/unbilled/tools/preview_unbilled_release', { data: { invoiceId } })).status(), { timeout: 15_000 }).toBe(200);
  await page.goto(`/invoices/${invoiceId}`);
  await page.getByRole('button', { name: 'Review source release' }).click();
  await page.getByRole('button', { name: 'Preview source release' }).click();
  await expect(page.getByText(/Release 1 time entries and 1 expenses/)).toBeVisible();
  await page.getByRole('button', { name: 'Confirm source release' }).click();
  await expect(page.getByRole('status').filter({ hasText: 'Sources released' })).toBeVisible();
  const released = await json(await api.get(`/api/invoices/${invoiceId}`));
  expect(released.status).toBe('VOID'); expect(released.billingSourcesReleasedAt).toBeTruthy();
  expect(released.billingSources).toEqual(invoice.billingSources);
  await page.getByRole('link', { name: 'Open invoice' }).click();
  await page.getByText('Original billed work', { exact: true }).click();
  await expect(page.getByText(/Sources released.*Original history is retained/)).toBeVisible();
  const candidates = await json(await api.post('/api/invoices/unbilled/tools/list_unbilled_candidates', { data: { clientId: client.id, kind: 'TIME' } }));
  expect(candidates.data.output.items.map((row: any) => row.id)).toContain(time.id);
});
